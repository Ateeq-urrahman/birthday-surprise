CREATE OR REPLACE FUNCTION public.record_game_win(
  p_user_id BIGINT,
  p_event_id TEXT,
  p_game TEXT,
  p_difficulty TEXT,
  p_challenge_date DATE
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  inserted_rows INTEGER;
  result JSONB;
BEGIN
  INSERT INTO public.user_progress_events (user_id, event_id)
  VALUES (p_user_id, p_event_id)
  ON CONFLICT (user_id, event_id) DO NOTHING;
  GET DIAGNOSTICS inserted_rows = ROW_COUNT;

  IF inserted_rows = 0 THEN
    SELECT jsonb_build_object(
      'games_played', games_played,
      'wins', wins,
      'completed_games', completed_games,
      'hard_wins', hard_wins,
      'daily_challenges_completed', daily_challenges_completed,
      'last_challenge_date', last_challenge_date
    ) INTO result
    FROM public.user_progress WHERE user_id = p_user_id;
    RETURN result;
  END IF;

  INSERT INTO public.user_progress (
    user_id, games_played, wins, completed_games, hard_wins,
    daily_challenges_completed, last_challenge_date
  )
  VALUES (
    p_user_id, 1, 1, jsonb_build_array(p_game),
    CASE WHEN p_difficulty = 'hard' THEN 1 ELSE 0 END,
    CASE WHEN p_challenge_date IS NULL THEN 0 ELSE 1 END,
    p_challenge_date
  )
  ON CONFLICT (user_id) DO UPDATE SET
    games_played = public.user_progress.games_played + 1,
    wins = public.user_progress.wins + 1,
    completed_games = CASE
      WHEN public.user_progress.completed_games ? p_game THEN public.user_progress.completed_games
      ELSE public.user_progress.completed_games || jsonb_build_array(p_game)
    END,
    hard_wins = public.user_progress.hard_wins + CASE WHEN p_difficulty = 'hard' THEN 1 ELSE 0 END,
    daily_challenges_completed = public.user_progress.daily_challenges_completed +
      CASE WHEN p_challenge_date IS NOT NULL AND
        public.user_progress.last_challenge_date IS DISTINCT FROM p_challenge_date THEN 1 ELSE 0 END,
    last_challenge_date = CASE
      WHEN p_challenge_date IS NOT NULL AND
        public.user_progress.last_challenge_date IS DISTINCT FROM p_challenge_date THEN p_challenge_date
      ELSE public.user_progress.last_challenge_date
    END;

  SELECT jsonb_build_object(
    'games_played', games_played,
    'wins', wins,
    'completed_games', completed_games,
    'hard_wins', hard_wins,
    'daily_challenges_completed', daily_challenges_completed,
    'last_challenge_date', last_challenge_date
  ) INTO result
  FROM public.user_progress WHERE user_id = p_user_id;
  RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION public.search_admin_users(search_term TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  escaped_term TEXT;
BEGIN
  escaped_term := '%' ||
    replace(replace(replace(search_term, E'\\', E'\\\\'), '%', E'\\%'), '_', E'\\_') ||
    '%';

  RETURN jsonb_build_object(
    'users',
    COALESCE((
      SELECT jsonb_agg(to_jsonb(matched) ORDER BY matched.id)
      FROM (
        SELECT id, username, name, birthday, pronouns, favorite_color, wish, role, created_at
        FROM public.users
        WHERE username ILIKE escaped_term ESCAPE E'\\'
          OR name ILIKE escaped_term ESCAPE E'\\'
        ORDER BY id
        LIMIT 200
      ) AS matched
    ), '[]'::jsonb),
    'total',
    (
      SELECT count(*)
      FROM public.users
      WHERE username ILIKE escaped_term ESCAPE E'\\'
        OR name ILIKE escaped_term ESCAPE E'\\'
    ),
    'limit', 200
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.is_login_rate_limited(p_key_hash TEXT)
RETURNS BOOLEAN
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT COALESCE((
    SELECT failures >= 10 AND window_started_at > now() - interval '15 minutes'
    FROM public.login_rate_limits
    WHERE key_hash = p_key_hash
  ), false);
$$;

CREATE OR REPLACE FUNCTION public.record_login_failure(p_key_hash TEXT)
RETURNS VOID
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  INSERT INTO public.login_rate_limits (key_hash, failures, window_started_at)
  VALUES (p_key_hash, 1, now())
  ON CONFLICT (key_hash) DO UPDATE SET
    failures = CASE
      WHEN public.login_rate_limits.window_started_at <= now() - interval '15 minutes' THEN 1
      ELSE public.login_rate_limits.failures + 1
    END,
    window_started_at = CASE
      WHEN public.login_rate_limits.window_started_at <= now() - interval '15 minutes' THEN now()
      ELSE public.login_rate_limits.window_started_at
    END;
$$;

CREATE OR REPLACE FUNCTION public.clear_login_failures(p_key_hash TEXT)
RETURNS VOID
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  DELETE FROM public.login_rate_limits WHERE key_hash = p_key_hash;
$$;

