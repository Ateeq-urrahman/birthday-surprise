CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE CHECK (username = lower(username)),
  password_salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  name TEXT NOT NULL,
  birthday DATE NOT NULL,
  pronouns TEXT NOT NULL DEFAULT '',
  favorite_color TEXT NOT NULL DEFAULT 'Pink',
  wish TEXT NOT NULL DEFAULT '',
  messages TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user'))
);

CREATE TABLE IF NOT EXISTS public.user_progress (
  user_id BIGINT PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
  games_played INTEGER NOT NULL DEFAULT 0,
  wins INTEGER NOT NULL DEFAULT 0,
  completed_games JSONB NOT NULL DEFAULT '[]'::jsonb,
  hard_wins INTEGER NOT NULL DEFAULT 0,
  daily_challenges_completed INTEGER NOT NULL DEFAULT 0,
  last_challenge_date DATE
);

CREATE TABLE IF NOT EXISTS public.user_progress_events (
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  event_id TEXT NOT NULL,
  PRIMARY KEY (user_id, event_id)
);

CREATE TABLE IF NOT EXISTS public.login_rate_limits (
  key_hash TEXT PRIMARY KEY,
  failures INTEGER NOT NULL DEFAULT 0,
  window_started_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_progress ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_progress_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.login_rate_limits ENABLE ROW LEVEL SECURITY;

